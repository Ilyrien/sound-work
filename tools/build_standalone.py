#!/usr/bin/env python3
"""Build a single-file copy of the audio check (no second request), for hosts
that serve one file. index.html + analyze.js stay the source of truth; this
output is generated, never edited by hand."""
import re, pathlib
here = pathlib.Path(__file__).parent
html = (here / "index.html").read_text()
js = (here / "analyze.js").read_text()
out = html.replace('<script src="analyze.js"></script>', "<script>\n" + js + "\n</script>")
out = out.replace("<!doctype html>", "<!doctype html>\n<!-- generated by build_standalone.py from index.html + analyze.js; edit those, not this -->", 1)
(here / "audio-check.html").write_text(out)
print("wrote", here / "audio-check.html", len(out), "bytes")
